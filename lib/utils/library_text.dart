import '../models/book.dart';

/// Normalises text for library sorting and searching.
///
/// `String.toLowerCase` keeps accents, so `Èdipo` would sort after `Z` and a
/// search for `edipo` would miss it. Folding the diacritics first gives the
/// order and matching a reader expects. The original text is still what the
/// UI displays.
String foldDiacritics(String input) {
  final buffer = StringBuffer();
  for (final rune in input.toLowerCase().runes) {
    final character = String.fromCharCode(rune);
    buffer.write(_latinFold[character] ?? character);
  }
  return buffer.toString();
}

/// Whether [book] matches a library search for [query].
///
/// An empty (or whitespace-only) query matches everything, so the home screen
/// does not need a separate "is searching" branch.
bool bookMatchesQuery(Book book, String query) {
  final needle = foldDiacritics(query.trim());
  if (needle.isEmpty) return true;
  return foldDiacritics(book.title).contains(needle) ||
      foldDiacritics(book.author).contains(needle);
}

